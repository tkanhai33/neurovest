from __future__ import annotations

import time

from spine.L4_runtime.patch_executor import run_patch_cycle
from spine.L4_runtime.convergence_engine import check_convergence

MAX_CYCLES = 5

def run_autonomous_loop(limit: int = 1000) -> dict:
    cycle = 0
    history = []

    while cycle < MAX_CYCLES:
        patch_result = run_patch_cycle(limit=limit)
        state = check_convergence(limit=limit)

        history.append({
            "cycle": cycle,
            "patched": patch_result,
            "state": state
        })

        # 🔥 FIX — stop immediately if nothing new was applied
        if patch_result["applied_count"] == 0:
            break

        if state["converged"]:
            break

        cycle += 1
        time.sleep(0.05)

    return {
        "cycles_run": cycle + 1,
        "final_state": history[-1]["state"] if history else None,
        "history": history
    }
