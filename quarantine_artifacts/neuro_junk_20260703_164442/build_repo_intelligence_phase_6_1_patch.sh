from __future__ import annotations

from pathlib import Path
import json

ROOT = Path(".").resolve()
MEM_FILE = ROOT / "backend/app/spine/L4_runtime/applied_patches/applied_set.json"

def _load() -> set:
    if not MEM_FILE.exists():
        return set()
    try:
        return set(json.loads(MEM_FILE.read_text()))
    except Exception:
        return set()

def already_applied(path: str) -> bool:
    return path in _load()

def mark_applied(path: str) -> None:
    applied = _load()
    applied.add(path)
    MEM_FILE.parent.mkdir(parents=True, exist_ok=True)
    MEM_FILE.write_text(json.dumps(sorted(list(applied)), indent=2))
PY


