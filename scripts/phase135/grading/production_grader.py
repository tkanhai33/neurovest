    @staticmethod
    def _build_check_index(
        capability: dict[str, Any],
    ) -> dict[str, dict[str, Any]]:
        index = {}

        for category in capability.get(
            "categories",
            [],
        ):
            for check in category.get("checks", []):
                check_id = check.get("check_id")

                if check_id:
                    index[check_id] = check

        return index

    @staticmethod
    def _count_test_checks(
        capability: dict[str, Any],
    ) -> int:
        count = 0

        for category in capability.get(
            "categories",
            [],
        ):
            for check in category.get("checks", []):
                check_id = str(
                    check.get("check_id", "")
                )

                label = str(
                    check.get("check", "")
                ).lower()

                if (
                    "test" in check_id.lower()
                    or "test" in label
                ):
                    if check.get("passed"):
                        count += 1

        return count

    @staticmethod
    def _safe_ratio(
        numerator: float,
        denominator: float,
    ) -> float:
        if denominator <= 0:
            return 0.0

        return round(
            numerator / denominator,
            6,
        )

    @staticmethod
    def _category_summary(
        category: dict[str, Any],
    ) -> dict[str, Any]:
        return {
            "category_id": category["category_id"],
            "category": category["category"],
            "score": category["score"],
            "maximum": category["maximum"],
            "percentage": category["percentage"],
            "status": category["status"],
        }

    @staticmethod
    def _category_status(
        percentage: float,
    ) -> str:
        if percentage < 40:
            return "Not Ready"

        if percentage < 60:
            return "Early"

        if percentage < 80:
            return "Conditional"

        if percentage < 90:
            return "Candidate"

        return "Ready"

    @staticmethod
    def _readiness_status(
        percentage: float,
    ) -> str:
        if percentage < 40:
            return "Not Ready"

        if percentage < 60:
            return "Early"

        if percentage < 80:
            return "Conditional"

        if percentage < 90:
            return "Production Candidate"

        return "Production Ready"
