#!/usr/bin/env python3

"""
Phase 135 Production Readiness Grader.

Consumes only evidence generated by earlier Phase 135 stages:

- repository discovery
- layer mapping
- dependency mapping
- import graph normalization
- runtime graph discovery
- contract discovery
- fintech capability grading
- AI capability grading

This grader does not:

- rescan the repository
- execute application code
- modify application code
- alter fintech or AI capability scores
- assign production-blocker severity
- approve deployment or live trading

Production readiness is graded independently across:

1. Architecture Integrity
2. Dependency Health
3. Runtime Readiness
4. Contract Readiness
5. Testing Readiness
6. Security and Identity
7. Operational Resilience
8. Persistence and Data Integrity
9. Observability and Auditability
10. Deployment Configuration
11. Fintech Production Readiness
12. AI Production Readiness
"""

from __future__ import annotations

from typing import Any, Callable


CheckEvaluator = Callable[[], tuple[bool, Any, str]]


class ProductionReadinessGrader:
    """
    Grade production readiness from existing Phase 135 evidence.
    """

    def __init__(
        self,
        discovery: dict[str, Any],
        layer_mapping: dict[str, Any],
        dependency_mapping: dict[str, Any],
        import_graph: dict[str, Any],
        runtime_graph: dict[str, Any],
        contract_discovery: dict[str, Any],
        fintech_capability: dict[str, Any],
        ai_capability: dict[str, Any],
    ) -> None:
        self.discovery = discovery
        self.layer_mapping = layer_mapping
        self.dependency_mapping = dependency_mapping
        self.import_graph = import_graph
        self.runtime_graph = runtime_graph
        self.contract_discovery = contract_discovery
        self.fintech_capability = fintech_capability
        self.ai_capability = ai_capability

        self.fintech_categories = {
            item["category_id"]: item
            for item in fintech_capability.get("categories", [])
        }

        self.ai_categories = {
            item["category_id"]: item
            for item in ai_capability.get("categories", [])
        }

        self.fintech_checks = self._build_check_index(
            fintech_capability
        )

        self.ai_checks = self._build_check_index(
            ai_capability
        )

        self.metrics = self._build_metrics()

    def grade(self) -> dict[str, Any]:
        categories = [
            self._grade_architecture_integrity(),
            self._grade_dependency_health(),
            self._grade_runtime_readiness(),
            self._grade_contract_readiness(),
            self._grade_testing_readiness(),
            self._grade_security_identity(),
            self._grade_operational_resilience(),
            self._grade_persistence_integrity(),
            self._grade_observability_auditability(),
            self._grade_deployment_configuration(),
            self._grade_fintech_readiness(),
            self._grade_ai_readiness(),
        ]

        total_score = round(
            sum(category["score"] for category in categories),
            2,
        )

        total_maximum = sum(
            category["maximum"] for category in categories
        )

        percentage = round(
            (
                total_score
                / total_maximum
                * 100
            )
            if total_maximum
            else 0.0,
            2,
        )

        readiness_status = self._readiness_status(percentage)

        failed_checks = []

        for category in categories:
            for check in category["checks"]:
                if check["passed"]:
                    continue

                failed_checks.append(
                    {
                        "category_id": category["category_id"],
                        "category": category["category"],
                        "check_id": check["check_id"],
                        "check": check["check"],
                        "observed": check["observed"],
                        "requirement": check["requirement"],
                        "points_available": check["maximum"],
                    }
                )

        strongest = sorted(
            categories,
            key=lambda item: (
                -item["percentage"],
                item["category"],
            ),
        )[:5]

        weakest = sorted(
            categories,
            key=lambda item: (
                item["percentage"],
                item["category"],
            ),
        )[:5]

        return {
            "grading_mode": "evidence_based_static_readiness",
            "application_executed": False,
            "repository_rescanned": False,
            "architecture_assumed": False,
            "fintech_score_modified": False,
            "ai_score_modified": False,
            "production_blockers_assessed": False,
            "deployment_approved": False,
            "live_trading_approved": False,
            "summary": {
                "category_count": len(categories),
                "total_score": total_score,
                "total_maximum": total_maximum,
                "percentage": percentage,
                "status": readiness_status,
                "checks_total": sum(
                    len(category["checks"])
                    for category in categories
                ),
                "checks_passed": sum(
                    category["checks_passed"]
                    for category in categories
                ),
                "checks_failed": sum(
                    category["checks_failed"]
                    for category in categories
                ),
                "readiness_gaps": len(failed_checks),
            },
            "categories": categories,
            "strongest_categories": [
                self._category_summary(item)
                for item in strongest
            ],
            "weakest_categories": [
                self._category_summary(item)
                for item in weakest
            ],
            "readiness_gaps": sorted(
                failed_checks,
                key=lambda item: (
                    item["category"],
                    item["check"],
                ),
            ),
            "metric_snapshot": dict(
                sorted(self.metrics.items())
            ),
            "scoring_contract": {
                "category_maximum": 100,
                "check_maximum": 20,
                "category_count": 12,
                "readiness_status_thresholds": {
                    "Not Ready": "0-39.99",
                    "Early": "40-59.99",
                    "Conditional": "60-79.99",
                    "Production Candidate": "80-89.99",
                    "Production Ready": "90-100",
                },
                "overall_score_is": (
                    "static production readiness evidence"
                ),
                "overall_score_is_not": [
                    "deployment approval",
                    "live trading approval",
                    "regulatory compliance certification",
                    "security certification",
                    "runtime correctness proof",
                    "production blocker assessment",
                ],
            },
            "limitations": [
                (
                    "Production readiness is inferred from static repository "
                    "evidence and previously generated capability grades."
                ),
                (
                    "No application process, database, broker, model provider, "
                    "network service, or frontend was executed."
                ),
                (
                    "Passing a readiness check does not prove runtime correctness, "
                    "security, reliability, or regulatory compliance."
                ),
                (
                    "Production blocker severity is intentionally deferred to "
                    "Stage 10."
                ),
            ],
        }

